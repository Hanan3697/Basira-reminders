import {DatabaseSync} from 'node:sqlite';
import {readFileSync,readdirSync} from 'node:fs';
import assert from 'node:assert/strict';
import {recordVisit,recordView,validView,stats,muscatDay,validVisit} from '../lib/analytics.mjs';
const sql=new DatabaseSync(':memory:');
for(const f of readdirSync(new URL('../drizzle/',import.meta.url)).filter(f=>f.endsWith('.sql')))sql.exec(readFileSync(new URL('../drizzle/'+f,import.meta.url),'utf8'));
const db={prepare(q){let args=[];return {bind(...a){args=a;return this},async run(){return sql.prepare(q).run(...args)},async first(){return sql.prepare(q).get(...args)},async all(){return {results:sql.prepare(q).all(...args)}}}},async batch(items){return Promise.all(items.map(x=>x.all()))}};
const now=Date.parse('2026-11-14T20:30:00Z');
assert.equal(muscatDay(now),'2026-11-15');
const a={visitor:'11111111-1111-4111-8111-111111111111',session:'22222222-2222-4222-8222-222222222222',section:'home'};
assert.ok(validVisit(a));assert.ok(!validVisit({...a,section:'unknown'}));
await recordVisit(db,a,now);await recordVisit(db,a,now);
await recordVisit(db,{...a,section:'reader'},now);
await recordVisit(db,{...a,session:'33333333-3333-4333-8333-333333333333'},now);
await recordVisit(db,{...a,session:'44444444-4444-4444-8444-444444444444',visitor:'55555555-5555-4555-8555-555555555555'},now-86400000);
assert.ok(validView({kind:'view',section:'home'}));assert.ok(!validView({kind:'view',section:'home',visitor:'private'}));
await recordView(db,{section:'home'},now);await recordView(db,{section:'home'},now);await recordView(db,{section:'reader'},now-86400000);
const result=await stats(db,now);
assert.equal(result.today.pageViews,2);assert.equal(result.today.sessions,2);assert.equal(result.all.sessions,3);assert.equal(result.today.visits,2);assert.equal(result.today.visitors,1);
assert.equal(result.all.visits,3);assert.equal(result.all.visitors,2);
assert.equal(result.sections.find(x=>x.section==='reader').visits,1);
assert.equal(result.daily.length,2);
console.log('PASS: access control, owner binding, optional-user deduplication, anonymous page-view aggregation, Oman date boundaries');

const later=await stats(db,now+90*86400000);
assert.equal(later.today.visits,0);
assert.equal(later.all.visits,3);
assert.equal(later.all.visitors,2);
assert.equal(later.daily.length,2);
assert.equal(later.sections.find(x=>x.section==='reader').visits,1);
console.log('PASS: totals, daily history and section counts retained after 90 days');
